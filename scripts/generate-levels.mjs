// Generates the campaign and the daily-puzzle pool, using every CPU core.
//   node scripts/generate-levels.mjs            (writes src/levels/campaign.js)
// Each accepted level is solver-proven; see scripts/levelgen/core.mjs for the filters.
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { cpus } from 'node:os';
import { writeFileSync } from 'node:fs';
import { rng, SPECS, candidate, evaluate, canonical } from './levelgen/core.mjs';

const WORLD_ORDER = ['meadow', 'river', 'snow', 'farm', 'canyon', 'woods'];
const PER_WORLD = 50;
const TARGET = { meadow: 80, river: 95, snow: 95, farm: 90, canyon: 90, woods: 90 };

if (!isMainThread) {
  const { world, seed, want, deadline } = workerData;
  const spec = SPECS[world];
  const r = rng(seed);
  let found = 0;
  while (found < want && Date.now() < deadline) {
    let mech = spec.mechanics;
    if (spec.anyMechanic) {
      mech = spec.mechanics.filter(() => r.chance(0.6));
      if (!mech.length) mech = [r.pick(spec.mechanics)];
    }
    const def = candidate(r, spec, mech);
    if (!def) continue;
    const e = evaluate(def, spec);
    if (!e) continue;
    found++;
    parentPort.postMessage(e);
  }
  parentPort.postMessage({ done: true });
} else {
  const { HANDMADE } = await import('../src/levels/handmade.js');
  const { WORLD_FRIENDS } = await import('../src/species.js');
  const { parseLevel, createState, solve, COMPANIONS } = await import('../src/logic.js');
  const threads = Math.max(1, cpus().length);
  const minutes = Number(process.env.GEN_MINUTES || 12);

  async function generate(world) {
    const results = [];
    const want = Math.ceil(TARGET[world] / threads);
    const deadline = Date.now() + minutes * 60000;
    await Promise.all(
      Array.from({ length: threads }, (_, k) =>
        new Promise((resolve, reject) => {
          const w = new Worker(new URL(import.meta.url), { workerData: { world, seed: 1000 * (WORLD_ORDER.indexOf(world) + 1) + k * 7919 + 1, want, deadline } });
          w.on('message', (m) => (m.done ? resolve() : results.push(m)));
          w.on('error', reject);
        }),
      ),
    );
    // Drop symmetric duplicates.
    const seen = new Set();
    const unique = results.filter((e) => {
      const c = canonical(e.def.map);
      if (seen.has(c)) return false;
      seen.add(c);
      return true;
    });
    unique.sort((a, b) => a.difficulty - b.difficulty);
    console.log(`${world}: ${unique.length} unique levels (${results.length} accepted)`);
    return unique;
  }

  // Pick `n` levels spread across the difficulty range, rising, with an easier breather every fifth.
  function curve(sorted, n) {
    const chosen = [];
    const used = new Set();
    for (let k = 0; k < n; k++) {
      let q = k / Math.max(1, n - 1);
      if (k % 5 === 4) q = Math.max(0, q - 0.25);
      let i = Math.round(q * (sorted.length - 1));
      while (used.has(i)) i = (i + 1) % sorted.length;
      used.add(i);
      chosen.push(sorted[i]);
    }
    const rest = sorted.filter((_, i) => !used.has(i));
    return { chosen, rest };
  }

  const strip = (e, pet, id) => ({ id, pet, map: e.def.map, ...(e.def.bees ? { bees: e.def.bees } : {}), par: e.def.par });

  const worlds = [];
  const daily = [];
  for (const [wi, world] of WORLD_ORDER.entries()) {
    const pool = await generate(world);
    const friends = WORLD_FRIENDS[wi];
    let levels;
    if (world === 'meadow') {
      const hand = HANDMADE.map((def, i) => {
        const level = parseLevel(def);
        const owned = COMPANIONS.slice(0, Math.min(i, 4));
        const sol = solve(createState(level, owned));
        return { id: `${world}-${i + 1}`, map: def.map, pet: level.pet, par: sol.moves };
      });
      const { chosen, rest } = curve(pool, PER_WORLD - hand.length);
      levels = [...hand, ...chosen.map((e, k) => strip(e, friends[k % friends.length], `${world}-${hand.length + k + 1}`))];
      daily.push(...rest.map((e) => ({ ...strip(e, friends[0], ''), world })));
    } else {
      const { chosen, rest } = curve(pool, PER_WORLD);
      levels = chosen.map((e, k) => strip(e, friends[k % friends.length], `${world}-${k + 1}`));
      daily.push(...rest.map((e) => ({ ...strip(e, friends[0], ''), world })));
    }
    worlds.push({ key: world, levels });
  }
  // Interleave the daily pool so consecutive days visit different worlds.
  const byWorld = WORLD_ORDER.map((w) => daily.filter((d) => d.world === w));
  const dailyOrdered = [];
  for (let i = 0; byWorld.some((l) => l.length); i++) {
    const list = byWorld[i % byWorld.length];
    if (list.length) dailyOrdered.push(list.shift());
  }
  dailyOrdered.forEach((d, i) => {
    d.id = `daily-${i + 1}`;
    d.pet = WORLD_FRIENDS[WORLD_ORDER.indexOf(d.world)][i % 4];
  });

  const out =
    `// Generated by scripts/generate-levels.mjs. Do not edit by hand.\n` +
    `// Every level is solver-verified; par is the minimum number of moves.\n` +
    `export const WORLDS = ${JSON.stringify(worlds)};\n` +
    `export const DAILY = ${JSON.stringify(dailyOrdered)};\n`;
  writeFileSync(new URL('../src/levels/campaign.js', import.meta.url), out);
  console.log(`wrote ${worlds.reduce((a, w) => a + w.levels.length, 0)} campaign levels and ${dailyOrdered.length} daily puzzles`);
}
